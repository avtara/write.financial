/**
 * Turns the Pencil variable snapshot (`design/tokens.json`) into `packages/ui/src/tokens.css`.
 *
 * Naming: every design variable `$name` becomes the CSS custom property `--name` (shadcn-style, so
 * `--card`, `--muted`, `--border`, `--input`, `--popover`, `--ring` line up with shadcn components),
 * and the Tailwind 4 theme key `--color-name` (`bg-card`, `text-muted-fg`, `border-border-input`).
 * Dark is the design default and lives on `:root`; light overrides it under `[data-theme='light']`.
 * Only variables present in the snapshot are emitted: the design has no `$violet-fg`, `$cyan-fg`,
 * or `$yellow-fg`, so neither does the CSS (plan §7).
 */
import { z } from 'zod';

/** Thrown when the snapshot does not have the shape this generator understands. */
export class TokensInputError extends Error {
  override name = 'TokensInputError';
}

/** String variables are font families; the role decides the Tailwind key and the fallback stack. */
const FONT_ROLES: Readonly<Record<string, { tailwind: string; fallback: string }>> = {
  font: { tailwind: '--font-sans', fallback: 'ui-sans-serif, system-ui, sans-serif' },
  mono: { tailwind: '--font-mono', fallback: 'ui-monospace, SFMono-Regular, Menlo, monospace' },
};

/** Lowercase, like Prettier prints CSS colors, so the committed file passes `format:check` unchanged. */
const Hex = z
  .string()
  .regex(/^#(?:[0-9A-Fa-f]{6}|[0-9A-Fa-f]{8})$/, 'Expected a #RRGGBB or #RRGGBBAA color')
  .transform((color) => color.toLowerCase());

const Themed = z
  .array(z.strictObject({ value: Hex, theme: z.strictObject({ mode: z.enum(['dark', 'light']) }) }))
  .refine(
    (entries) => entries.length === 2 && entries[0]?.theme.mode !== entries[1]?.theme.mode,
    'A themed color needs exactly one dark and one light value',
  )
  .transform((entries) => {
    const [first, second] = entries as [(typeof entries)[0], (typeof entries)[0]];
    return first.theme.mode === 'dark'
      ? { dark: first.value, light: second.value }
      : { dark: second.value, light: first.value };
  });

const Variable = z.discriminatedUnion('type', [
  z.strictObject({ type: z.literal('color'), value: z.union([Hex, Themed]) }),
  z.strictObject({
    type: z.literal('string'),
    value: z.string().regex(/^[A-Za-z0-9][A-Za-z0-9 ]*$/, 'Expected a font family name'),
  }),
]);

const Snapshot = z.strictObject({
  themes: z.strictObject({ mode: z.tuple([z.literal('dark'), z.literal('light')]) }),
  variables: z.record(z.string().regex(/^[a-z][a-z0-9]*(?:-[a-z0-9]+)*$/, 'Invalid variable name'), Variable),
});

/** Validates the Pencil variable snapshot and renders `tokens.css` (custom properties + Tailwind `@theme inline`). */
export function generateTokensCss(input: unknown): string {
  const parsed = Snapshot.safeParse(input);
  if (!parsed.success) throw new TokensInputError(z.prettifyError(parsed.error));

  const dark = ['color-scheme: dark;'];
  const light = ['color-scheme: light;'];
  const colorKeys = ['--color-*: initial;'];
  const fontKeys: string[] = [];
  // Code-unit order keeps the output independent of the export order and of the machine locale.
  const names = Object.keys(parsed.data.variables).sort((a, b) => (a < b ? -1 : 1));
  for (const name of names) {
    const variable = parsed.data.variables[name] as z.infer<typeof Variable>;
    if (variable.type === 'string') {
      const role = FONT_ROLES[name];
      if (!role) {
        throw new TokensInputError(`$${name}: string variables must be one of ${Object.keys(FONT_ROLES).join(', ')}`);
      }
      dark.push(`--${name}: '${variable.value}', ${role.fallback};`);
      fontKeys.push(`${role.tailwind}: var(--${name});`);
    } else if (typeof variable.value === 'string') {
      dark.push(`--${name}: ${variable.value};`);
      colorKeys.push(`--color-${name}: var(--${name});`);
    } else {
      dark.push(`--${name}: ${variable.value.dark};`);
      light.push(`--${name}: ${variable.value.light};`);
      colorKeys.push(`--color-${name}: var(--${name});`);
    }
  }

  const block = (selector: string, lines: readonly string[]): string =>
    `${selector} {\n${lines.map((line) => `  ${line}\n`).join('')}}\n`;
  return [
    '/* SPDX-License-Identifier: AGPL-3.0-only */\n',
    '/* Generated by tools/tokens-from-pen from design/tokens.json. Do not edit: run `pnpm tokens`. */\n\n',
    block(":root,\n[data-theme='dark']", dark),
    '\n',
    block("[data-theme='light']", light),
    '\n',
    '/* Utilities read the variables above, so they follow the active theme. The default palette is removed. */\n',
    block('@theme inline', [...colorKeys, ...fontKeys]),
  ].join('');
}
