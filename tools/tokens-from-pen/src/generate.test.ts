import { readFileSync } from 'node:fs';
import { describe, expect, it } from 'vitest';
import { generateTokensCss, TokensInputError } from './generate.ts';

const themes = { mode: ['dark', 'light'] };
const themed = (dark: string, light: string) => ({
  type: 'color',
  value: [
    { value: dark, theme: { mode: 'dark' } },
    { value: light, theme: { mode: 'light' } },
  ],
});
const snapshot = (variables: Record<string, unknown>) => ({ themes, variables });

describe('generateTokensCss', () => {
  it('renders dark on :root, light overrides, fixed colors once, fonts, and the Tailwind theme', () => {
    const css = generateTokensCss(
      snapshot({
        mono: { type: 'string', value: 'Geist Mono' },
        fg: themed('#FAFAFA', '#0A0A0A'),
        'on-accent': { type: 'color', value: '#FFFFFF' },
        font: { type: 'string', value: 'Geist' },
        card: {
          type: 'color',
          // Light first: the order inside a themed value does not matter.
          value: [
            { value: '#FFFFFF', theme: { mode: 'light' } },
            { value: '#121212AA', theme: { mode: 'dark' } },
          ],
        },
      }),
    );
    expect(css).toBe(
      [
        '/* SPDX-License-Identifier: AGPL-3.0-only */',
        '/* Generated by tools/tokens-from-pen from design/tokens.json. Do not edit: run `pnpm tokens`. */',
        '',
        ':root,',
        "[data-theme='dark'] {",
        '  color-scheme: dark;',
        '  --card: #121212aa;',
        '  --fg: #fafafa;',
        "  --font: 'Geist', ui-sans-serif, system-ui, sans-serif;",
        "  --mono: 'Geist Mono', ui-monospace, SFMono-Regular, Menlo, monospace;",
        '  --on-accent: #ffffff;',
        '}',
        '',
        "[data-theme='light'] {",
        '  color-scheme: light;',
        '  --card: #ffffff;',
        '  --fg: #0a0a0a;',
        '}',
        '',
        '/* Utilities read the variables above, so they follow the active theme. The default palette is removed. */',
        '@theme inline {',
        '  --color-*: initial;',
        '  --color-card: var(--card);',
        '  --color-fg: var(--fg);',
        '  --color-on-accent: var(--on-accent);',
        '  --font-sans: var(--font);',
        '  --font-mono: var(--mono);',
        '}',
        '',
      ].join('\n'),
    );
  });

  it('is deterministic regardless of the export order', () => {
    const a = { fg: themed('#FAFAFA', '#0A0A0A'), bg: themed('#0A0A0A', '#F7F7F8') };
    const b = { bg: a.bg, fg: a.fg };
    expect(generateTokensCss(snapshot(a))).toBe(generateTokensCss(snapshot(b)));
  });

  it('emits every design variable and never invents missing -fg tokens', () => {
    const json = JSON.parse(readFileSync(new URL('../../../design/tokens.json', import.meta.url), 'utf8')) as {
      variables: Record<string, { type: string }>;
    };
    const css = generateTokensCss(json);
    for (const [name, variable] of Object.entries(json.variables)) {
      expect(css).toContain(`  --${name}: `);
      if (variable.type === 'color') expect(css).toContain(`  --color-${name}: var(--${name});`);
    }
    for (const missing of ['violet-fg', 'cyan-fg', 'yellow-fg']) {
      expect(css).not.toContain(`--${missing}:`);
      expect(css).not.toContain(`--color-${missing}:`);
    }
  });

  it.each([
    ['a non-object', null],
    ['missing variables', { themes }],
    ['a third theme mode', { themes: { mode: ['dark', 'light', 'dim'] }, variables: {} }],
    ['unknown top-level keys', { themes, variables: {}, extra: 1 }],
    ['an unknown variable type', snapshot({ radius: { type: 'number', value: 4 } })],
    ['an invalid name', snapshot({ 'Bad Name': { type: 'color', value: '#FFFFFF' } })],
    ['a non-hex color', snapshot({ fg: { type: 'color', value: 'red' } })],
    ['a short hex color', snapshot({ fg: { type: 'color', value: '#FFF' } })],
    [
      'a themed color with one mode',
      snapshot({ fg: { type: 'color', value: [{ value: '#FFFFFF', theme: { mode: 'dark' } }] } }),
    ],
    [
      'a themed color with a duplicate mode',
      snapshot({
        fg: {
          type: 'color',
          value: [
            { value: '#FFFFFF', theme: { mode: 'dark' } },
            { value: '#000000', theme: { mode: 'dark' } },
          ],
        },
      }),
    ],
    [
      'an unknown theme mode',
      snapshot({ fg: { type: 'color', value: [{ value: '#FFFFFF', theme: { mode: 'dim' } }] } }),
    ],
    ['a font family with CSS syntax', snapshot({ font: { type: 'string', value: "Geist'; color: red" } })],
  ])('rejects %s', (_label, input) => {
    expect(() => generateTokensCss(input)).toThrow(TokensInputError);
  });

  it('rejects string variables that are not a known font role', () => {
    expect(() => generateTokensCss(snapshot({ heading: { type: 'string', value: 'Geist' } }))).toThrow(
      new TokensInputError('$heading: string variables must be one of font, mono'),
    );
  });
});
